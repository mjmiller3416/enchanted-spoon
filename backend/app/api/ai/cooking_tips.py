"""API router for cooking tips."""

from fastapi import APIRouter, Depends, HTTPException, Request
from sqlalchemy.orm import Session

from app.dtos.cooking_tip_dtos import CookingTipResponseDTO
from app.services.ai.cooking_tips import get_cooking_tip_service
from app.api.auth import require_within_usage_limit
from app.core.rate_limit import LIGHT_IP_LIMITS, LIGHT_USER_LIMITS, ip_limiter, limiter
from app.database.db import get_session
from app.models.user import User
from app.api.errors import internal_error

router = APIRouter()


_tip_limit = require_within_usage_limit(
    "ai_suggestions_requested",
    user_limits=LIGHT_USER_LIMITS,
    ip_limits=LIGHT_IP_LIMITS,
)


@router.get("", response_model=CookingTipResponseDTO)
@limiter.limit("10/minute")
@ip_limiter.limit("30/minute")
async def get_cooking_tip(
    request: Request,
    session: Session = Depends(get_session),
    current_user: User = Depends(_tip_limit),
) -> CookingTipResponseDTO:
    """
    Get a random cooking tip generated by AI.

    Returns:
        Response with a cooking tip on success
    """
    del request
    try:
        service = get_cooking_tip_service()
        result = service.generate_tip()

        if not result.success:
            raise HTTPException(
                status_code=500, detail=result.error or "Tip generation failed"
            )

        return result

    except HTTPException:
        raise
    except ValueError as e:
        raise internal_error()
    except Exception as e:
        raise internal_error("Tip generation failed. Please try again.")
